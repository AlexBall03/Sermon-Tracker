export type OccurrenceActionResult = ActionResult & { id?: string };
export type VenueActionResult = ActionResult & {
  venue?: { id: string; name: string; locality: string | null };
  /** When the name is taken: the venue that has it, so the caller can use that one. */
  existingId?: string;
};
export type ContextActionResult = ActionResult & {
  context?: { id: string; name: string };
  /** When the name is taken: the context that has it, so the caller can use that one. */
  existingId?: string;
};

type Messages = Dictionaries["preaching"]["actions"];

/** The messages and the schemas, in the account's language. */
async function context() {
  const locale = await getLocale();
  return { t: dictionary(locale, "preaching").actions, schemas: preachingSchemas(locale) };
}

function firstIssue(error: { issues: { message: string }[] }, fallback: string): ActionResult {
  return { ok: false, message: error.issues[0]?.message || fallback };
}

function refresh(sermonId?: string) {
  revalidatePath(routes.library);
  if (sermonId) revalidatePath(`${routes.library}/${sermonId}`);
}

/*
 * As with the idea actions: each one authorises itself when it runs, takes
 * the owner from the session, and accepts nothing that could name another.
 * A sermon, venue, context, or occasion that is missing and one that belongs
 * to someone else are the same answer. Reading history is not an action;
 * pages call the services themselves.
 *
 * None of these changes an idea. Recording that a sermon was preached leaves
 * its status, its classifications, and its place in the library as they were.
 */

/** Records that a sermon was preached. `id` may be generated by the browser so a retry cannot record it twice. */
export async function recordOccurrence(
  input: unknown,
  id?: unknown,
): Promise<OccurrenceActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas } = await context();

  const parsed = schemas.occurrenceInput.safeParse(input);
  if (!parsed.success) return firstIssue(parsed.error, t.invalid);
  const occurrenceId = id === undefined ? undefined : occurrenceIdSchema.safeParse(id);
  if (occurrenceId && !occurrenceId.success) return { ok: false, message: t.invalid };

  let outcome: occurrences.CreateOutcome;
  try {
    outcome = await occurrences.createOccurrence(
      getDb(),
      actor.user.id,
      parsed.data,
      occurrenceId?.data.toLowerCase(),
    );
  } catch (error) {
    console.error("Preaching occurrence create failed:", describeDatabaseError(error));
    return { ok: false, message: t.notRecorded };
  }
  switch (outcome.status) {
    case "missing":
      return { ok: false, message: t.missingSermon };
    case "not_sermon":
      return { ok: false, message: t.notSermon };
    case "unknown_venue":
      return { ok: false, message: t.unknownVenue };
    case "unknown_context":
      return { ok: false, message: t.unknownContext };
    case "unavailable":
      return { ok: false, message: t.notRecorded };
    case "existing":
      // A retry: it was recorded the first time, and that is the answer again.
      return { ok: true, message: t.recorded, id: outcome.occurrence.id };
    case "created":
      refresh(outcome.occurrence.sermonId);
      return { ok: true, message: t.recorded, id: outcome.occurrence.id };
  }
}

/** Changes an occasion. A field left out is left alone; one given as null is cleared. */
export async function updateOccurrence(id: unknown, input: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas } = await context();

  const occurrenceId = occurrenceIdSchema.safeParse(id);
  if (!occurrenceId.success) return { ok: false, message: t.invalid };
  const parsed = schemas.occurrenceUpdate.safeParse(input);
  if (!parsed.success) return firstIssue(parsed.error, t.invalid);

  let outcome: occurrences.UpdateOutcome;
  try {
    outcome = await occurrences.updateOccurrence(
      getDb(),
      actor.user.id,
      occurrenceId.data,
      parsed.data,
    );
  } catch (error) {
    console.error("Preaching occurrence update failed:", describeDatabaseError(error));
    return { ok: false, message: t.changesNotSaved };
  }
  if (outcome.status === "missing") return { ok: false, message: t.missing };
  if (outcome.status === "unknown_venue") return { ok: false, message: t.unknownVenue };
  if (outcome.status === "unknown_context") return { ok: false, message: t.unknownContext };
  refresh(outcome.occurrence.sermonId);
  return { ok: true, message: t.changesSaved };
}

/** Removes one occasion from history. The sermon and every other occasion stay. */
export async function deleteOccurrence(id: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t } = await context();

  const occurrenceId = occurrenceIdSchema.safeParse(id);
  if (!occurrenceId.success) return { ok: false, message: t.invalid };

  try {
    if (!(await occurrences.deleteOccurrence(getDb(), actor.user.id, occurrenceId.data))) {
      return { ok: false, message: t.missing };
    }
  } catch (error) {
    console.error("Preaching occurrence delete failed:", describeDatabaseError(error));
    return { ok: false, message: t.notRemoved };
  }
  refresh();
  return { ok: true, message: t.removed };
}

function venueSaved(result: venues.VenueResult, t: Messages): VenueActionResult {
  if (!result.ok) {
    if (result.reason === "missing") return { ok: false, message: t.missingVenue };
    return {
      ok: false,
      message: t.duplicateVenue,
      ...(result.existingId ? { existingId: result.existingId } : {}),
    };
  }
  refresh();
  const { id, name, locality } = result.venue;
  return { ok: true, message: t.venueSaved, venue: { id, name, locality } };
}

export async function createVenue(input: unknown): Promise<VenueActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas } = await context();

  const parsed = schemas.venueInput.safeParse(input);
  if (!parsed.success) return firstIssue(parsed.error, t.invalid);

  try {
    return venueSaved(await venues.createVenue(getDb(), actor.user.id, parsed.data), t);
  } catch (error) {
    console.error("Venue create failed:", describeDatabaseError(error));
    return { ok: false, message: t.venueNotSaved };
  }
}

