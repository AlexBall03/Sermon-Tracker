/** Deletes a venue that no occasion names. One that history names is kept. */
export async function deleteVenue(id: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t } = await context();

  const venueId = venueIdSchema.safeParse(id);
  if (!venueId.success) return { ok: false, message: t.invalid };

  try {
    const result = await venues.deleteVenue(getDb(), actor.user.id, venueId.data);
    if (!result.ok) {
      return {
        ok: false,
        message: result.reason === "missing" ? t.missingVenue : t.venueInUse(result.count),
      };
    }
  } catch (error) {
    console.error("Venue delete failed:", describeDatabaseError(error));
    return { ok: false, message: t.venueNotDeleted };
  }
  refresh();
  return { ok: true, message: t.venueDeleted };
}

