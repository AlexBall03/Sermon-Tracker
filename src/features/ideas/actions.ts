"use server";

import { revalidatePath } from "next/cache";

import { getDb } from "@/db";
import { describeDatabaseError } from "@/db/types";
import { authorize } from "@/features/auth/access";
import { formatReferences } from "@/features/scripture/reference";
import { dictionary } from "@/i18n";
import { getLocale } from "@/i18n/server";
import type { ActionResult } from "@/lib/action-result";
import { routes } from "@/lib/site";
import * as service from "./ideas";
import { ideaLimits } from "./model";
import { ideaIdSchema, ideaKindSchema, ideaSchemas } from "./schemas";
import { UnknownTagError } from "./tags";

export type IdeaActionResult = ActionResult & { id?: string };

/** The messages and the schemas, in the account's language. */
async function context() {
  const locale = await getLocale();
  return { locale, t: dictionary(locale, "ideas").actions, schemas: ideaSchemas(locale) };
}

function firstIssue(error: { issues: { message: string }[] }, fallback: string): ActionResult {
  return { ok: false, message: error.issues[0]?.message ?? fallback };
}

function refresh(id?: string) {
  revalidatePath(routes.library);
  revalidatePath(routes.dashboard);
  if (id) revalidatePath(`${routes.library}/${id}`);
}

/*
 * Every action authorises itself when it runs and takes the owner from the
 * session. Nothing in the input can name an owner, and the schema drops any
 * key it does not know.
 *
 * An idea that is missing and one that belongs to someone else are the same
 * answer (`missing`), and so are a tag that is missing and one that is someone
 * else's (`unknownTag`): nothing was saved either way.
 */

/** Saves a new idea. `id` may be generated by the browser so a retry cannot save it twice. */
export async function createIdea(input: unknown, id?: unknown): Promise<IdeaActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas } = await context();

  const parsed = schemas.ideaInput.safeParse(input);
  if (!parsed.success) return firstIssue(parsed.error, t.couldNotSave);
  const ideaId = id === undefined ? undefined : ideaIdSchema.safeParse(id);
  if (ideaId && !ideaId.success) return { ok: false, message: t.invalid };

  try {
    const idea = await service.createIdea(getDb(), actor.user.id, parsed.data, ideaId?.data);
    if (!idea) return { ok: false, message: t.notSaved };
    refresh();
    return { ok: true, message: t.saved, id: idea.id };
  } catch (error) {
    if (error instanceof UnknownTagError) return { ok: false, message: t.unknownTag };
    console.error("Idea create failed:", describeDatabaseError(error));
    return { ok: false, message: t.notSaved };
  }
}

export async function updateIdea(id: unknown, input: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas } = await context();

  const ideaId = ideaIdSchema.safeParse(id);
  if (!ideaId.success) return { ok: false, message: t.invalid };
  const parsed = schemas.ideaInput.safeParse(input);
  if (!parsed.success) return firstIssue(parsed.error, t.changesNotSaved);

  try {
    const idea = await service.updateIdea(getDb(), actor.user.id, ideaId.data, parsed.data);
    if (!idea) return { ok: false, message: t.missing };
  } catch (error) {
    if (error instanceof UnknownTagError) return { ok: false, message: t.unknownTag };
    console.error("Idea update failed:", describeDatabaseError(error));
    return { ok: false, message: t.yourChangesNotSaved };
  }
  refresh(ideaId.data);
  return { ok: true, message: t.changesSaved };
}

export type AttachActionResult = ActionResult & {
  /** The idea the passages went to, so the caller can offer the way to it. */
  id?: string;
  /** How many passages were added now; none when the idea had them all. */
  added?: number;
};

/**
 * Adds passages to one of the caller's ideas, from the Bible reader or from
 * saved Scripture. Nothing else about the idea changes, and a passage it
 * already has is not added again.
 */
export async function attachScripture(input: unknown): Promise<AttachActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t, schemas, locale } = await context();

  const parsed = schemas.attachInput.safeParse(input);
  if (!parsed.success) {
    // A malformed idea ID says nothing about the passage; a passage that does not exist does.
    const [issue] = parsed.error.issues;
    return issue?.path[0] === "references"
      ? firstIssue(parsed.error, t.invalid)
      : { ok: false, message: t.invalid };
  }
  const { ideaId, references } = parsed.data;

  let outcome: service.AttachOutcome;
  try {
    outcome = await service.attachReferences(getDb(), actor.user.id, ideaId, references);
  } catch (error) {
    console.error("Scripture attach failed:", describeDatabaseError(error));
    return { ok: false, message: t.passageNotAdded };
  }
  if (outcome.status === "missing") return { ok: false, message: t.missing };
  if (outcome.status === "full") {
    return {
      ok: false,
      message:
        outcome.room === 0
          ? t.full(ideaLimits.references)
          : t.room(outcome.room, references.length),
    };
  }

  const { idea, added, already } = outcome;
  const title = `“${idea.title}”`;
  if (added.length === 0) {
    return {
      ok: true,
      id: idea.id,
      added: 0,
      message: t.alreadyOn(formatReferences(already, locale), title),
    };
  }
  refresh(idea.id);
  return {
    ok: true,
    id: idea.id,
    added: added.length,
    message: t.added(formatReferences(added, locale), title),
  };
}

export async function changeIdeaKind(id: unknown, kind: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t } = await context();

  const ideaId = ideaIdSchema.safeParse(id);
  const parsed = ideaKindSchema.safeParse(kind);
  if (!ideaId.success || !parsed.success) return { ok: false, message: t.invalid };

  try {
    const idea = await service.setIdeaKind(getDb(), actor.user.id, ideaId.data, parsed.data);
    if (!idea) return { ok: false, message: t.missing };
  } catch (error) {
    console.error("Idea reclassification failed:", describeDatabaseError(error));
    return { ok: false, message: t.notReclassified };
  }
  refresh(ideaId.data);
  return { ok: true, message: t.reclassified(parsed.data) };
}

export async function deleteIdea(id: unknown): Promise<ActionResult> {
  const actor = await authorize("active");
  if (!actor.ok) return actor;
  const { t } = await context();

  const ideaId = ideaIdSchema.safeParse(id);
  if (!ideaId.success) return { ok: false, message: t.invalid };

  try {
    if (!(await service.deleteIdea(getDb(), actor.user.id, ideaId.data))) {
      return { ok: false, message: t.missing };
    }
  } catch (error) {
    console.error("Idea delete failed:", describeDatabaseError(error));
    return { ok: false, message: t.notDeleted };
  }
  refresh();
  return { ok: true, message: t.deleted };
}
