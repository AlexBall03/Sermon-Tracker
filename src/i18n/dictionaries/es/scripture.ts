const colors: Record<HighlightColor, string> = {
  yellow: "Amarillo",
  green: "Verde",
  blue: "Azul",
  red: "Rojo",
};

const lower = (color: HighlightColor) => colors[color].toLowerCase();

/** "amarillo y azul", "amarillo, azul y rojo". */
function listed(present: readonly HighlightColor[]) {
  const names = present.map(lower);
  if (names.length <= 1) return names.join("");
  return `${names.slice(0, -1).join(", ")} y ${names.at(-1)}`;
}

const counted = (count: number, one: string, many: string) =>
  `${count} ${count === 1 ? one : many}`;

